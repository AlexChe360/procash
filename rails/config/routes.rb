Rails.application.routes.draw do
  root "pages#home"
  get "/documentation", to: "documentation#index"
  post "/assistant/messages", to: "assistant#create"
  get "/t/:token", to: "bills#show"
  get "/health", to: "pages#health"
  get "/login", to: "sessions#new"
  post "/login", to: "sessions#create"
  get "/admin/login", to: "sessions#new"
  post "/admin/login", to: "sessions#create"
  post "/admin/logout", to: "sessions#destroy"
  post "/dashboard/logout", to: "sessions#destroy"
  get "/connect", to: "connection_requests#new"
  post "/connect", to: "connection_requests#create"
  get "/connect/success", to: "connection_requests#success"
  get "/invite/success", to: "invitations#success"
  post "/invite/activate", to: "invitations#activate"
  get "/invite/:token", to: "invitations#show", constraints: { token: /[^\/]+/ }, format: false
  get "/dashboard", to: "dashboard#index"
  get "/dashboard/settings", to: "account_settings#show"
  post "/dashboard/settings/profile", to: "account_settings#profile"
  post "/dashboard/settings/password", to: "account_settings#password"
  get "/admin/settings", to: "account_settings#show"
  post "/admin/settings/profile", to: "account_settings#profile"
  post "/admin/settings/password", to: "account_settings#password"
  get "/dashboard/payments", to: "payments#index"
  scope "/dashboard/merchants/:id/outlets/:outlet_id/acquiring" do
    post "requests", to: "acquiring_requests#create"
    post "requests/:request_id/primary", to: "acquiring_requests#primary"
  end
  get "/admin/acquiring", to: "admin_acquiring#index"
  get "/admin/acquiring/requests/:request_id", to: "admin_acquiring#show"
  post "/admin/acquiring/requests/:request_id/review", to: "admin_acquiring#review"
  post "/admin/acquiring/requests/:request_id/configure", to: "admin_acquiring#configure"
  post "/admin/acquiring/requests/:request_id/decision", to: "admin_acquiring#decision"
  get "/admin/acquiring/outlets/:outlet_id", to: "admin_acquiring#outlet"
  scope "/admin/acquiring/outlets/:outlet_id" do
    post "connections", to: "acquiring_connections#create"
    post "connections/:connection_id", to: "acquiring_connections#update"
    post "connections/:connection_id/primary", to: "acquiring_connections#primary"
    post "connections/:connection_id/toggle", to: "acquiring_connections#toggle"
  end
  get "/dashboard/merchants/:id", to: "dashboard#company"
  get "/dashboard/merchants/:id/outlets", to: "dashboard#company"
  post "/dashboard/merchants/:id/outlets", to: "dashboard#create_outlet"
  get "/dashboard/merchants/:id/outlets/:outlet_id/tables/:table_id/qr.svg", to: "dashboard#qr"
  get "/dashboard/merchants/:id/outlets/:outlet_id/tables/:table_id/qr/design", to: "dashboard#qr_design"
  get "/dashboard/merchants/:id/outlets/:outlet_id/tables/:table_id/qr/print", to: "dashboard#qr_print"
  post "/dashboard/merchants/:id/outlets/:outlet_id/tables/:table_id/qr/logo", to: "dashboard#qr_logo"
  get "/dashboard/merchants/:id/outlets/:outlet_id", to: "dashboard#outlet"
  post "/dashboard/merchants/:id/outlets/:outlet_id/tables", to: "dashboard#create_table"
  post "/dashboard/merchants/:id/outlets/:outlet_id/tip-settings", to: "dashboard#tips"
  get "/admin", to: redirect("/demo/requests")
  get "/demo/merchants/new", to: "admin#new_merchant"
  post "/demo/merchants/new", to: "admin#preview_merchant"
  get "/demo/dashboard", to: "admin#index"
  get "/demo/requests", to: "admin#requests"
  get "/demo/merchants", to: "admin#merchants"
  get "/demo/requests/:id", to: "admin#show"
  post "/demo/requests/:id/review", to: "admin#review"
  post "/demo/requests/:id/decision/:action_name", to: "admin#decision"
  post "/demo/requests/:id/merchant", to: "admin#merchant"
  post "/demo/requests/:id/invitation", to: "admin#invitation"
  scope "/dashboard/merchants/:id/outlets/:outlet_id/pos" do
    post "connections", to: "pos_configurations#create"
    post "connections/:connection_id/check", to: "pos_configurations#verify"
    get "connections/:connection_id/setup", to: "pos_configurations#setup"
    post "connections/:connection_id/binding", to: "pos_configurations#bind"
    get "tables", to: "pos_configurations#tables"
    post "tables/:table_id/link", to: "pos_configurations#link"
    post "activation/check", to: "pos_configurations#check"
    post "activation/enable", to: "pos_configurations#enable"
  end

end
